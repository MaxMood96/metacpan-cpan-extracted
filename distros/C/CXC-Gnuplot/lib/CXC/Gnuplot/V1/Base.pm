package CXC::Gnuplot::V1::Base;

use v5.38;
use Object::Pad;

our $VERSION = 'v0.29.3';

class CXC::Gnuplot::V1::Base : abstract;

use Lexical::Import qw( Ref::Util is_plain_hashref);

method BUILDARGS : common ( @args ) {
    return $args[0]->%* if @args == 1 && is_plain_hashref( $args[0] );
    return @args;
}

1;

