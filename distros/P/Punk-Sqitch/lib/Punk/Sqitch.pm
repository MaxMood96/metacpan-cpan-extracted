=head1 NAME

Punk::Sqitch - schema change management for Punk applications, on Sqitch

=head1 SYNOPSIS

    # the database punk.yml configures is the target, every time
    punk sqitch deploy
    punk sqitch deploy --env production
    punk sqitch status --database analytics
    punk sqitch add users -n 'users table'

    # the pieces, from Perl
    my $t = Punk::Sqitch->target_for({ dsn => 'dbi:Pg:host=db;dbname=shop',
                                       user => 'shop', password => $pw });
    # $t->{uri}      db:pg://shop@db/shop
    # $t->{engine}   pg
    # $t->{password} $pw   - handed to Sqitch through $SQITCH_PASSWORD, never the URI

=head1 DESCRIPTION

L<Sqitch|App::Sqitch> manages database schema as a plan of changes with
deploy, revert and verify scripts, recorded in a registry in the database
itself. Punk::Sqitch makes it the path of least resistance in a Punk
application: C<punk sqitch> runs any Sqitch command against the database
the application is configured for, so there is one description of that
database - the C<database> keyword, or the C<database> block of
F<config/punk.yml> with its secret behind C<$env> - and Sqitch is told the
target on every run rather than keeping its own copy in F<sqitch.conf>.

The install needs one thing the Perl side cannot supply: Sqitch runs
scripts through the database's own client, C<sqlite3> (3.3.9 or later),
C<psql> or C<mysql>, so the host that deploys needs that binary on its
C<PATH>. The application's workers never do.

=head2 Installing App::Sqitch

As of App::Sqitch v1.6.1 its own F<t/engine.t> dies on a recent
L<Test::MockModule> (the test reads C<$@> after an C<unmock> that clears
it), so C<cpanm App::Sqitch> reports a failure with no failed assertion
and does not install. C<cpanm --notest App::Sqitch> does.

=head1 THE TARGET

=head2 target_for(\%database)

Maps a C<database> options hash - C<dsn>, and optionally C<user> and
C<password> - to a Sqitch target:

    dbi:SQLite:dbname=var/app.db                     db:sqlite:var/app.db
    dbi:Pg:dbname=shop                               db:pg:shop
    dbi:Pg:host=h;port=5433;dbname=shop   + user     db:pg://user@h:5433/shop
    dbi:Pg:dbname=shop;sslmode=require               db:pg:shop?sslmode=require
    dbi:mysql:database=shop;host=h        + user     db:mysql://user@h/shop
    dbi:MariaDB:database=shop                        db:mysql:shop

Returns C<< { uri, engine, password } >>. The URI B<never carries the
password>: Sqitch reads one from C<$SQITCH_PASSWORD>, and a password that
is not in the URI is not in C<sqitch -v>'s output, a process listing or a
log. C<run> localises the variable around each command.

DSN keys other than the host, port and database name become query
parameters (C<sslmode>, C<application_name>, ...), which is how
L<URI::db> spells them and what Sqitch's engines hand to DBI. A driver
other than SQLite, Pg, mysql and MariaDB croaks naming it: declare the
target in F<sqitch.conf> for those.

=head2 Other engines

Mapped from the DBI driver out of the box: SQLite, Pg, mysql and
MariaDB, Oracle (C<sid> or C<service_name> as the database), Firebird
and ClickHouse. Two escape hatches cover the rest, both as keys on the
C<database> options - the keyword's or the F<punk.yml> block's:

    database dsn => 'dbi:Pg:dbname=shop;host=h', sqitch_engine => 'cockroach';
    database dsn => 'dbi:ODBC:DSN=warehouse',
             sqitch_target => 'db:vertica://etl@warehouse.internal/shop',
             user => 'etl', password => $pw;

C<sqitch_engine> keeps the mapping and replaces the engine name, for the
engines that ride on another's driver - CockroachDB and Yugabyte on
C<DBD::Pg>. C<sqitch_target> is the application's own URI, used as it is
whatever the DSN says (the password still travels separately). A driver
with neither croaks naming both ways out, and a third:

=head2 engine_for($driver => \%spec)

    Punk::Sqitch->engine_for(Vertica => { engine => 'vertica', name => 'database' });

Register, or replace, the mapping for a DBI driver: C<engine> is Sqitch's
engine name, C<name> the DSN key holding the database name, C<aliases>
other keys that also name it, and C<< path => 1 >> for a file-backed
engine whose name is a path and whose URI has no authority, the SQLite
shape. C<engines> lists the engine names currently mapped.

The check (C<pending>) knows where Pg, CockroachDB, Yugabyte, Oracle,
Vertica, Snowflake and Exasol keep their registry (a schema) and where
MySQL and ClickHouse do (a database beside the target); for an engine it
does not know - Firebird keeps a separate database file behind the
server - it reports an error rather than a guess, and C<punk sqitch
status> still works. The model skeleton has types for SQLite, Pg,
CockroachDB, Yugabyte, MySQL, Oracle and Firebird (C<register_types>
adds an engine), and the client probe knows every client Sqitch 1.6
looks for (C<register_client> adds one).

=head1 THE APPLICATION

=head2 The sqitch directory

Everything Sqitch owns lives together under F<sqitch/> in the application
root - the plan, the conf and the three script directories:

    myapp/
      app.psgi
      config/punk.yml
      lib/MyApp.pm
      sqitch/
        sqitch.conf
        sqitch.plan
        deploy/  revert/  verify/

C<punk sqitch init> creates it and every command runs from it, so the
application root stays the application's. A project with those files
loose in the root - the layout before this, or one made by C<sqitch init>
by hand - is used where it is; nothing has to move.

Because each project runs from its own directory, a relative SQLite path
is resolved against the B<application root>, in F<punk.yml> and in a
C<--target> of your own alike, and the directory it names is created on
C<deploy> if it is missing.

=head2 project_dir($root)

The directory holding the application's Sqitch project: F<sqitch/> under
the root when it holds a plan or a conf, the root itself when that does,
and F<sqitch/> for a project that does not exist yet.

=head2 ensure_target_dir($target, $root)

The directory a SQLite target lives in, created when missing (relative
paths against C<$root>); nothing for any other engine. Returns what it
made, or undef.

=head2 find_root($dir?)

The directory holding F<app.psgi>, walking up from C<$dir> (default the
current directory) - the rule every C<punk> command uses.

=head2 databases_for(root => $dir, env => $name, registrar => $app?)

The configured databases as C<< { name => \%options } >>, with C<default>
for the unnamed one. From the application's registrar when it can answer
(C<< $app->databases >>, Punk 0.31), else from F<config/punk.yml> resolved
for the environment through L<Punk::Config> - secrets included, because
Sqitch needs the real password.

=head2 database_for(\%databases, $name?)

One database's options, or a croak listing the names there are.

=head1 THE CHECK

    my $r = Punk::Sqitch->pending(root => $root, database => \%db);
    # { project, plan_file, registry, deployed => N, pending => [...],
    #   drift => undef|"...", error => undef|"..." }

Is the schema behind the code? The plan against the registry, computed
here and used twice: by C<punk sqitch pending> as a deploy gate and by
L<Punk::Plugin::Sqitch> at boot. Sqitch's own C<status> prints the answer
and exits 0 either way, and its C<check> reports something else - a
deployed script edited since, by hash - so this is the other half.

=head2 pending(root => $dir, database => \%db, %opts)

C<pending> is the plan's changes beyond the number the registry holds for
the project. B<Counts, not names>: a reworked change is in the plan twice
under one name and in the registry twice with two ids, so the first N
plan entries are what N deployed rows stand for. The Nth deployed name is
checked against the Nth plan entry, and a mismatch - or more rows than the
plan has entries - is C<drift>: something deployed here that the plan does
not describe, which no C<deploy> will fix. A registry that does not exist
yet is "nothing deployed", everything pending, and not an error; one that
cannot be reached or read is C<error>, and the caller decides - the boot
check warns and starts.

Options: C<target> (from C<target_for>, computed otherwise), C<conf> (from
C<read_conf>, read from F<sqitch.conf> in the root otherwise), C<plan_file>
(from C<plan_file_for> otherwise). A missing plan croaks naming the path
and C<punk sqitch init>.

One C<SELECT> through DBI, with no L<App::Sqitch> loaded: the boot check
runs in a web worker's parent, where loading a Moo application to answer
a yes/no question would be the wrong cost.

=head2 read_conf($file)

F<sqitch.conf> as a flat hash, C<section.key> and C<section.sub.key>
(C<[engine "sqlite"]> gives C<engine.sqlite.*>), comments and quotes
handled. Only the project's own file: a registry renamed in
F<~/.sqitch/sqitch.conf> is not seen.

=head2 conf_get(\%conf, $key, $engine?, $target?)

One key by Sqitch's precedence: C<target.$target.$key>, then
C<engine.$engine.$key>, then C<core.$key>.

=head2 plan_file_for($root, \%conf, $engine?)

C<plan_file> from the conf (relative to the root), else C<top_dir> (or the
root) joined with F<sqitch.plan>.

=head2 read_plan($file)

C<< { project, uri, changes => [names], tags => [names], deps => { change
=> [deps] }, requires => [projects] } >>: the C<%project> and C<%uri>
pragmas, every change's name in order (a reworked one twice), the tags,
each change's dependencies, and the other projects those dependencies
name (C<project:change>). A plan without C<%project> croaks.

=head2 pending_all(root => $dir, database => \%db, projects => \@projects?)

C<pending> for every project in the list (C<projects> when none is
given), in the list's order: a plugin project's plan from its own
directory, the registry the target's.

=head2 projects(root => $dir, app_only => 0|1)

The projects a target verb runs over: the plugins' in deploy order -
found by loading the application class (C<load_app>) so its plugins
register them - then the application's own. Each is
C<< { name, dir, plan_file, conf, plan, plugin => 0|1 } >>. With
C<app_only> the application's alone, and nothing is loaded.

=head2 app_project(root => $dir, conf => \%conf?, plan_file => $file?)

The application's own project entry.

=head2 project_list(\%app_project, \@plugin_projects)

The plugins' projects then the application's, checking the one policy
the arrangement needs: with plugin projects the registry keeps its
default name (L<Punk::Plugin::Sqitch/"The registry keeps its default name">).

=head2 app_class_for($root)

The application class named in F<app.psgi>, without running it.

=head2 load_app($root)

Load that class - F<lib/> under the root on C<@INC> - with the boot check
held off, so its plugins register their projects. Croaks naming the class
when it will not load.

=head2 target_abs($target, $root)

A SQLite target made absolute against the root, for a run whose working
directory is a plugin's project; other engines' targets already are.

=head2 registry_for(\%db, $target, \%conf)

Where Sqitch keeps the registry for a target, as its engines decide it:
for SQLite a B<file> - the registry name (C<sqitch> unless the conf says
otherwise) in place of the target's basename, keeping its extension, so
F<app.db> gives F<sqitch.db> beside it, an absolute registry as is; for
PostgreSQL a B<schema> in the target database; for MySQL a B<database> on
the same server. C<< { engine, name, kind, path?, connect => [@dbi_args] } >>.

=head1 SCAFFOLDING

=head2 project_name_for($app_class)

A Sqitch project name for an application class: lowercased, C<::> to
C<_>, always inside Sqitch's C<[A-Za-z][\w-]*>.

=head2 skeleton(meta => \%meta, engine => $engine, %opts)

The C<deploy>, C<revert> and C<verify> scripts for a L<Punk::Model>'s
table, from its metadata (C<table>, C<fields>, C<field>, C<primary>), for
C<sqlite>, C<pg> or C<mysql>. Types map C<integer>, C<string>, C<number>
and C<boolean>; the primary key becomes the engine's autoincrement when it
is an integer; C<required> is C<NOT NULL>; a type with no mapping is
C<text> with a comment asking for one. Options C<project>, C<change> and
C<model> fill the header. Returns C<< { deploy, revert, verify } >>.

=head2 register_types($engine => \%types)

    Punk::Sqitch->register_types(vertica => {
        integer => 'BIGINT', string => 'VARCHAR(4000)', number => 'FLOAT',
        boolean => 'BOOLEAN', primary_integer => 'IDENTITY PRIMARY KEY',
        txn => 0, false => 'FALSE' });

The skeleton's types for an engine: C<integer>, C<string>, C<number> and
C<boolean> for L<Punk::Model>'s field types, C<primary_integer> for the
integer primary key's whole declaration, C<txn> whether the scripts wrap
in C<BEGIN>/C<COMMIT>, C<false> the WHERE-nothing predicate. Replaces a
built-in engine's as readily as it adds one.

=head2 register_client($engine => \%client)

    Punk::Sqitch->register_client(mydb => { name => 'mydb-cli', args => ['--version'],
                                            min => '2.0', alternatives => ['mydb'] });

The client an engine deploys through: C<name> on C<PATH>, C<alternatives>
the other names to try, C<args> what prints its version, C<min> the oldest
Sqitch accepts.

=head2 client_for($engine, \%conf)

The client binary the engine deploys through - Sqitch's default name, or
C<[engine "x"] client> from the conf - found on C<PATH> and asked its
version: C<< { name, path, version, ok, why } >>. A C<sqlite3> older than
3.3.9, which Sqitch refuses, is not C<ok>.

=head1 RUNNING SQITCH

=head2 run(verb => $verb, args => \@args, target => $target?, cwd => $dir?, verbosity => $n?)

One Sqitch command, in-process, through L<App::Sqitch::Command>. For a
verb that takes a target (C<deploy>, C<revert>, C<verify>, C<status>,
C<log>, C<check>, C<checkout>, C<rebase>, C<upgrade>, C<bundle>) the
target's URI is passed as C<--target> unless the arguments already carry
one, and its password as C<$SQITCH_PASSWORD> for the duration. With C<cwd> the
command runs from that directory and the previous one is restored
afterwards, whatever happens. Returns the exit code by Sqitch's own
rules: 0, the exception's code for one of Sqitch's (a failed deploy is 2),
2 for a usage error, with the message on C<STDERR> as C<punk sqitch: ...>.

In-process rather than C<exec sqitch> because L<Punk::Command>'s C<main>
localises C<STDOUT> and C<STDERR> and returns an exit code, so a test of
C<punk sqitch status> reads both without spawning. The C<sqitch> binary
is not required on C<PATH>; the engine's client is.

=head2 takes_target($verb)

Whether a verb accepts C<--target>.

